-- Run in Supabase Dashboard > SQL Editor.
-- Profiles
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default 'IR-Chart User',
  username text unique,
  bio text,
  avatar_url text,
  created_at timestamptz not null default now()
);

-- Posts
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  caption text not null default '',
  image_url text,
  created_at timestamptz not null default now()
);

-- Direct messages
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now(),
  constraint no_self_message check (sender_id <> receiver_id)
);

create index if not exists posts_created_at_idx on public.posts(created_at desc);
create index if not exists messages_sender_receiver_idx on public.messages(sender_id, receiver_id, created_at);

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.messages enable row level security;

-- Profiles are visible to signed-in users; each user edits only their own.
create policy "Signed-in users can view profiles" on public.profiles
for select to authenticated using (true);
create policy "Users can insert own profile" on public.profiles
for insert to authenticated with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles
for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

-- Signed-in users can view posts; users can only create/delete their own posts.
create policy "Signed-in users can view posts" on public.posts
for select to authenticated using (true);
create policy "Users can create own posts" on public.posts
for insert to authenticated with check (auth.uid() = user_id);
create policy "Users can delete own posts" on public.posts
for delete to authenticated using (auth.uid() = user_id);

-- Only the sender and recipient can read a direct message.
create policy "Participants can read messages" on public.messages
for select to authenticated using (auth.uid() = sender_id or auth.uid() = receiver_id);
create policy "Sender can send message" on public.messages
for insert to authenticated with check (auth.uid() = sender_id and sender_id <> receiver_id);

-- Storage bucket for post photos.
insert into storage.buckets (id, name, public)
values ('post-images', 'post-images', true)
on conflict (id) do nothing;

create policy "Signed-in users can upload post images" on storage.objects
for insert to authenticated with check (bucket_id = 'post-images' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "Public can view post images" on storage.objects
for select using (bucket_id = 'post-images');
create policy "Owners can delete post images" on storage.objects
for delete to authenticated using (bucket_id = 'post-images' and (storage.foldername(name))[1] = auth.uid()::text);
